#!/usr/bin/env node
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const KNOWN_FRONTMATTER_KEYS = new Set(["name", "description", "model", "tools"]);

const scriptDir = dirname(fileURLToPath(import.meta.url));
const defaultSourceDir = resolve(scriptDir, "../../../agents");
const defaultCodexHome = process.env.CODEX_HOME
  ? resolve(process.env.CODEX_HOME)
  : join(homedir(), ".codex");

const options = parseArgs(process.argv.slice(2));
const sourceDir = resolve(options.sourceDir ?? defaultSourceDir);
const outDir = resolve(options.outDir ?? join(defaultCodexHome, "agents"));

const warnings = [];
const results = [];

const entries = await readdir(sourceDir, { withFileTypes: true }).catch((error) => {
  throw new Error(`cannot read agent source directory ${sourceDir}: ${error.message}`);
});
const files = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
  .map((entry) => join(sourceDir, entry.name))
  .sort();

if (files.length === 0) {
  throw new Error(`no agent markdown files found in ${sourceDir}`);
}

if (!options.dryRun) {
  await mkdir(outDir, { recursive: true });
}

for (const file of files) {
  const source = await readFile(file, "utf8");
  const agent = convertAgentMarkdown(source, file, relative(sourceDir, file), warnings);
  const target = join(outDir, `${agent.name}.toml`);
  const current = existsSync(target) ? await readFile(target, "utf8") : undefined;

  if (current === agent.toml) {
    results.push({ status: "unchanged", target });
    continue;
  }
  if (!options.dryRun) {
    await writeFile(target, agent.toml, "utf8");
  }
  const status = current === undefined ? "installed" : "updated";
  const dryRunStatus = current === undefined ? "would install" : "would update";
  results.push({ status: options.dryRun ? dryRunStatus : status, target });
}

for (const result of results) {
  console.log(`${result.status}: ${result.target}`);
}
for (const warning of warnings) {
  console.warn(`warning: ${warning}`);
}
console.log(options.dryRun
  ? "dry run complete; no files were written"
  : "Codex agent install complete. Restart Codex or start a new thread before using newly installed agents.");

function convertAgentMarkdown(source, sourcePath, displaySourcePath, warnings) {
  const { frontmatter, body } = splitFrontmatter(source, sourcePath);
  const name = required(frontmatter, "name", sourcePath);
  const description = required(frontmatter, "description", sourcePath);
  const prompt = extractAgentPrompt(body).trim();
  if (!prompt) throw new Error(`${sourcePath} has no agent prompt body`);

  for (const key of Object.keys(frontmatter)) {
    if (!KNOWN_FRONTMATTER_KEYS.has(key)) {
      warnings.push(`${sourcePath} has unsupported frontmatter key '${key}'`);
    }
  }

  const tools = frontmatter.tools;
  const developerInstructions = [
    `Converted from PARA-ZK clients/agents/${displaySourcePath}.`,
    "",
    "Required tool assumptions:",
    tools
      ? `- Source agent requested Claude tools: ${tools}. In Codex, use the current session's equivalent tools. The PARA-ZK weaver requires the Optsidian MCP command runner, exposed as \`mcp__optsidian__command_run\`.`
      : "- Use the current Codex session tools available to this agent.",
    "- Do not use Bash for Optsidian/para-zk commands when the source prompt says to use the Optsidian MCP command runner.",
    "",
    prompt
  ].join("\n");

  const toml = [
    "# Generated by PARA-ZK codex-setup. Edit clients/agents/*.md in the plugin source, then reinstall.",
    `name = ${tomlString(name)}`,
    `description = ${tomlString(description)}`,
    `developer_instructions = ${tomlMultilineString(developerInstructions)}`,
    ""
  ].join("\n");

  return { name, toml };
}

function splitFrontmatter(source, sourcePath) {
  if (!source.startsWith("---\n")) {
    throw new Error(`${sourcePath} must start with YAML frontmatter`);
  }
  const end = source.indexOf("\n---\n", 4);
  if (end === -1) {
    throw new Error(`${sourcePath} has unterminated YAML frontmatter`);
  }
  const yaml = source.slice(4, end);
  const body = source.slice(end + "\n---\n".length);
  return { frontmatter: parseSimpleYaml(yaml, sourcePath), body };
}

function parseSimpleYaml(yaml, sourcePath) {
  const record = {};
  for (const [index, line] of yaml.split(/\r?\n/).entries()) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = trimmed.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) {
      throw new Error(`${sourcePath}:${index + 2} uses unsupported YAML syntax`);
    }
    record[match[1]] = unquoteYamlScalar(match[2].trim());
  }
  return record;
}

function unquoteYamlScalar(value) {
  if (
    (value.startsWith("\"") && value.endsWith("\""))
    || (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function extractAgentPrompt(body) {
  const match = body.match(/<Agent_Prompt>\s*([\s\S]*?)\s*<\/Agent_Prompt>/);
  return match ? match[1] : body;
}

function required(record, key, sourcePath) {
  const value = record[key]?.trim();
  if (!value) throw new Error(`${sourcePath} frontmatter is missing '${key}'`);
  return value;
}

function tomlString(value) {
  return JSON.stringify(value);
}

function tomlMultilineString(value) {
  if (!value.includes("'''")) {
    return `'''\n${value}\n'''`;
  }
  return tomlString(value);
}

function parseArgs(args) {
  const parsed = {
    dryRun: false,
    outDir: undefined,
    sourceDir: undefined
  };
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--dry-run") {
      parsed.dryRun = true;
    } else if (arg === "--force") {
      // Kept for compatibility with older instructions; installs overwrite by default.
    } else if (arg === "--out-dir") {
      parsed.outDir = readArgValue(args, ++i, arg);
    } else if (arg === "--source-dir") {
      parsed.sourceDir = readArgValue(args, ++i, arg);
    } else if (arg === "--help" || arg === "-h") {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return parsed;
}

function readArgValue(args, index, flag) {
  const value = args[index];
  if (!value) throw new Error(`${flag} requires a value`);
  return value;
}

function printHelp() {
  console.log(`Usage: install-codex-agents.mjs [--dry-run] [--force] [--out-dir PATH] [--source-dir PATH]

Convert PARA-ZK clients/agents/*.md files into Codex custom-agent TOML files.
Existing generated target files are overwritten by default. --force is accepted
for compatibility with older instructions and has no effect.

Defaults:
  source: ${defaultSourceDir}
  output: ${join(defaultCodexHome, "agents")}
`);
}
